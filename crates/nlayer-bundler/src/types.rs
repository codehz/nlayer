#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declared_exports_are_the_native_modules() {
        let files = type_files();
        let text = |name: &str| {
            files
                .iter()
                .find(|(path, _)| path == name)
                .unwrap()
                .1
                .clone()
        };
        let runtime = text("@nlayer/runtime.d.ts");
        let ui = text("@nlayer/ui.d.ts");
        for name in nlayer_js::native_module_exports("@nlayer/runtime").unwrap() {
            assert!(
                runtime.contains(&format!("export function {name}")),
                "{name} missing from runtime declarations"
            );
        }
        for name in nlayer_js::native_module_exports("@nlayer/ui").unwrap() {
            if name == "platform" {
                assert!(ui.contains("export const platform"));
                continue;
            }
            assert!(
                ui.contains(&format!("export function {name}")),
                "{name} missing from ui declarations"
            );
        }
        assert!(ui.contains("readonly os: \"web\" | \"ios\" | \"android\""));
        assert!(ui.contains("activeStyle?:"));
        assert!(ui.contains("hoverStyle?:"));
        assert!(ui.contains("focusStyle?:"));
        assert!(!ui.contains("disabledStyle"));
        assert!(!runtime.contains("resource"));
        assert!(text("styles.d.ts").contains("gridTemplateColumns?:"));
        assert!(!text("styles.d.ts").contains("boxShadow?:"));
        assert!(text("assets.d.ts").contains("declare module \"*.png\""));
        assert!(!text("assets.d.ts").contains("*.svg"));
        assert!(text("@nlayer/jsx-runtime.d.ts").contains("export function jsx"));
        let globals = text("globals.d.ts");
        assert!(globals.contains("declare function fetch"));
        assert!(globals.contains("declare const console"));
        assert!(!globals.contains("subtle"), "crypto.subtle is absent in v1");
        assert!(
            !globals.contains("export "),
            "globals are ambient, not a module"
        );
    }
}
