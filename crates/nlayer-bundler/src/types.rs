//! TypeScript declarations `build` writes. Style properties come from
//! [`nlayer_core::typescript::style_declarations`]; the export names are the
//! native modules'.

/// Files under the build's `types` directory (`path`, contents).
pub fn type_files() -> Vec<(String, String)> {
    vec![
        ("styles.d.ts".to_owned(), style_file()),
        ("assets.d.ts".to_owned(), assets()),
        ("@nlayer/runtime.d.ts".to_owned(), runtime().to_owned()),
        ("@nlayer/ui.d.ts".to_owned(), ui().to_owned()),
        ("@nlayer/test.d.ts".to_owned(), TEST.to_owned()),
        (
            "@nlayer/jsx-runtime.d.ts".to_owned(),
            JSX_RUNTIME.to_owned(),
        ),
    ]
}

fn style_file() -> String {
    format!(
        "// Generated by nlayer from its style table: do not edit.\n\n{}",
        nlayer_core::typescript::style_declarations()
    )
}

fn assets() -> String {
    use std::fmt::Write as _;
    let mut out = String::from(
        "// Generated by nlayer: what an image import gives.\n\
         \n\
         /** A bundled image (`import icon from \"./icon.png\"`). `url` is an `asset:/` URI. */\n\
         export interface ImageAsset {\n\
           url: string;\n\
           size: { width: number; height: number };\n\
           /** Densities the bundle ships, `1` first, when `@2x` siblings exist. */\n\
           scales?: readonly number[];\n\
         }\n",
    );
    for ext in ["png", "jpg", "jpeg", "webp"] {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  const asset: ImageAsset;\n  export default asset;\n}}\n"
        );
    }
    out
}

