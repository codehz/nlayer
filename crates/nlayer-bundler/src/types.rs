/// Drops leading `//` comment lines and the blank line that follows them.
fn body_after_header(text: &str) -> &str {
    let mut rest = text;
    loop {
        let Some(line_end) = rest.find('\n') else {
            return if rest.starts_with("//") { "" } else { rest };
        };
        if rest[..line_end].starts_with("//") {
            rest = &rest[line_end + 1..];
            continue;
        }
        break;
    }
    rest.strip_prefix('\n').unwrap_or(rest)
}

