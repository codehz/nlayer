//! TypeScript declarations `build` writes. Style properties come from
//! [`nlayer_core::typescript::style_declarations`]; the export names are the
//! native modules'.

/// Files under the build's `types` directory (`path`, contents).
pub fn type_files() -> Vec<(String, String)> {
    vec![
        ("styles.d.ts".to_owned(), style_file()),
        ("globals.d.ts".to_owned(), GLOBALS.to_owned()),
        ("assets.d.ts".to_owned(), assets()),
        ("@nlayer/runtime.d.ts".to_owned(), runtime().to_owned()),
        ("@nlayer/ui.d.ts".to_owned(), ui().to_owned()),
        ("@nlayer/test.d.ts".to_owned(), TEST.to_owned()),
        (
            "@nlayer/jsx-runtime.d.ts".to_owned(),
            JSX_RUNTIME.to_owned(),
        ),
    ]
}

